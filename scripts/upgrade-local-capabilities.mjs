import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { prepareHostedPluginInstall } from '../packages/harness-host-plugin/prepare-install.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const {dataHome}=JSON.parse(fs.readFileSync(path.join(root,'config/desktop-install.local.json'),'utf8'));
const data=fs.realpathSync(dataHome),clientFile=path.join(data,'harness-host/client.json');
const client=JSON.parse(fs.readFileSync(clientFile,'utf8'));
if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(client.endpoint))throw Error('Unexpected host endpoint');
const token=fs.readFileSync(client.tokenFile,'utf8').trim();
const response=await fetch(client.endpoint+'/health',{headers:{authorization:'Bearer '+token},signal:AbortSignal.timeout(10000)});
const health=await response.json();
if(health.protocol!=='xiaozhushou-harness-host-v1'||health.activeTasks!==0)throw Error('Host is busy or identity differs; no update applied.');
const install=fs.realpathSync(client.installDirectory);
if(!install.startsWith(data+path.sep)||!fs.existsSync(path.join(install,'.xiaozhushou-host-plugin')))throw Error('Not a product-owned plugin directory');
const backup=path.join(root,'dist','local-upgrade-backup-0.3.11');fs.mkdirSync(backup,{recursive:true});
for(const item of fs.readdirSync(install,{withFileTypes:true}))if(item.isFile()||item.name==='locale')fs.cpSync(path.join(install,item.name),path.join(backup,item.name),{recursive:item.isDirectory(),force:false,errorOnExist:true});
const updated=await prepareHostedPluginInstall({productDataRoot:data,workspacesRoot:health.workspacesRoot,installDirectory:install,port:Number(new URL(client.endpoint).port),provider:health.provider,model:health.model});
console.log(JSON.stringify({prepared:true,revision:updated.revision,installDirectory:install,backup,dependencySource:updated.dependencySource,previousActiveTasks:health.activeTasks}));
